import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const app=readFileSync(new URL("../app.js",import.meta.url),"utf8");
const css=readFileSync(new URL("../styles.css",import.meta.url),"utf8");
const config=readFileSync(new URL("../config.js",import.meta.url),"utf8");
const vercel=JSON.parse(readFileSync(new URL("../vercel.json",import.meta.url),"utf8"));
const ids=["home","category","article","search","login","register","account","reporter","admin","news","auto","applications","users","video","epaper","contact","about","privacy"];
assert.match(html,/<html lang="bn">/);
assert.match(html,/type="module" src="\/app.js"/);
assert.match(html,/id="app"/);
for(const id of ids)assert.ok(app.includes('["'+id+'"'),'Missing route '+id);
assert.match(app,/signInWithPassword/);
assert.match(app,/signUp\(\{phone/);
assert.match(app,/approve_auto_news/);
assert.match(app,/review_reporter_application/);
assert.match(app,/set_user_role/);
assert.match(app,/news-media/);
assert.match(app,/published_at/);
assert.match(app,/status==="published"/);
assert.match(app,/service-role|secret key/i)===false;
assert.match(config,/sb_publishable_/);
assert.doesNotMatch(config,/service_role|service-role|secret/i);
assert.match(css,/@media\(max-width:760px\)/);
assert.equal(vercel.rewrites[0].destination,"/index.html");
assert.ok(vercel.headers.length>=4);
console.log("TribuneBangla smoke tests passed: route set, Supabase auth, moderation, role APIs, media bucket, responsive layout and security headers.");
